-- Reference schema for the target API (Phase 3.5C-2). Used by both profiles:
-- lab (local, seeded at small/medium/large scale) and cloud (Neon, small scale).
-- Only primary keys here; foreign keys, unique constraints and secondary indexes are
-- added after loading (constraints.sql), which is faster and keeps index names fixed.

CREATE TABLE categories (
  id          integer PRIMARY KEY,
  name        text NOT NULL
);

CREATE TABLE users (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  email       text NOT NULL,
  city        text NOT NULL,
  created_at  timestamptz NOT NULL
);

CREATE TABLE products (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id integer NOT NULL,
  name        text NOT NULL,
  description text NOT NULL,
  specs       jsonb NOT NULL,
  price       numeric(10, 2) NOT NULL,
  stock       integer NOT NULL,
  created_at  timestamptz NOT NULL
);

CREATE TABLE orders (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     bigint NOT NULL,
  status      text NOT NULL,
  total       numeric(12, 2) NOT NULL,
  created_at  timestamptz NOT NULL
);

CREATE TABLE order_items (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    bigint NOT NULL,
  product_id  bigint NOT NULL,
  quantity    integer NOT NULL,
  unit_price  numeric(10, 2) NOT NULL
);
